def main() -> None:
    parser = argparse.ArgumentParser(description="生成演示用企业文档")
    parser.add_argument("--out", default="data/raw", help="输出目录")
    parser.add_argument("--dry-run", action="store_true", help="只打印文件名")
    parser.add_argument("--force", action="store_true", help="覆盖已存在的同名文件")
    args = parser.parse_args()

    out_dir = ROOT / args.out
    docs = build_documents()
    print(f"将生成 {len(docs)} 篇文档")

    if args.dry_run:
        for name, _ in docs[:10]:
            print("  ·", name)
        print("  ...")
        return

    out_dir.mkdir(parents=True, exist_ok=True)
    created, skipped = 0, 0
    for name, content in docs:
        path = out_dir / name
        if path.exists() and not args.force:
            skipped += 1
            continue
        path.write_text(content, encoding="utf-8")
        created += 1

    print(f"已写入 {created} 篇到 {out_dir}" + (f"，跳过已存在 {skipped} 篇" if skipped else ""))
    print("下一步：")
    print("  python main.py chunk     # 重新切片")
    print("  python main.py index     # 重建索引")


if __name__ == "__main__":
    main()
